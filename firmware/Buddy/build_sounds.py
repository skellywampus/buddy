"""Convert the eight supplied WAVs into 16 kHz mono IMA ADPCM in flash.

Run `python3 firmware/Buddy/build_sounds.py` after replacing a source clip.
Requires ffmpeg. This is a mechanical asset generator, not firmware logic.
"""
from pathlib import Path
import subprocess
import struct
import wave

ROOT = Path(__file__).resolve().parent
SOURCES = tuple(f"New-sound-{number}" for number in range(1, 9))
OUTPUT = ROOT / "sounds_generated.h"
PLAYBACK_FRAMES = 24000  # 1.5 s; the remaining supplied audio is silence.


def convert(name):
    source = ROOT / "sounds" / f"{name}.wav"
    with wave.open(str(source), "rb") as wav:
        assert wav.getnchannels() == 2 and wav.getsampwidth() == 2 and wav.getframerate() == 44100, source
    pcm = subprocess.check_output([
        "ffmpeg", "-hide_banner", "-loglevel", "error", "-i", str(source),
        "-ar", "16000", "-ac", "1", "-f", "s16le", "-",
    ])
    samples = struct.unpack("<" + "h" * (len(pcm) // 2), pcm)
    if len(samples) < PLAYBACK_FRAMES or (
        len(samples) > PLAYBACK_FRAMES and
        max(abs(s) for s in samples[PLAYBACK_FRAMES:]) > 103
    ):
        raise ValueError(f"{source} has audible audio beyond the bundled 1.5-second cut")
    return samples[:PLAYBACK_FRAMES]


STEPS = (7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31,
         34, 37, 41, 45, 50, 55, 60, 66, 73, 80, 88, 97, 107, 118, 130,
         143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449,
         494, 544, 598, 658, 724, 796, 876, 963, 1060, 1166, 1282, 1411,
         1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024, 3327, 3660, 4026,
         4428, 4871, 5358, 5894, 6484, 7132, 7845, 8630, 9493, 10442, 11487,
         12635, 13899, 15289, 16818, 18500, 20350, 22385, 24623, 27086,
         29794, 32767)
INDEX_CHANGE = (-1, -1, -1, -1, 2, 4, 6, 8)


def encode(samples):
    """Standard IMA ADPCM, one independent clip with an exact first sample."""
    predictor, index = samples[0], 0
    codes = []
    for sample in samples[1:]:
        step = STEPS[index]
        diff = sample - predictor
        code = 8 if diff < 0 else 0
        remaining = abs(diff)
        if remaining >= step:
            code |= 4
            remaining -= step
        if remaining >= step // 2:
            code |= 2
            remaining -= step // 2
        if remaining >= step // 4:
            code |= 1
        change = step >> 3
        if code & 4: change += step
        if code & 2: change += step >> 1
        if code & 1: change += step >> 2
        predictor = max(-32768, min(32767, predictor - change if code & 8 else predictor + change))
        index = max(0, min(88, index + INDEX_CHANGE[code & 7]))
        codes.append(code)
    return tuple(codes[i] | (codes[i + 1] << 4 if i + 1 < len(codes) else 0)
                 for i in range(0, len(codes), 2))


def main():
    lines = ["// Generated by build_sounds.py from the user-supplied WAV files.",
             "#pragma once", "#include <stdint.h>", "#include <Arduino.h>", ""]
    for name in SOURCES:
        symbol = "buddy_adpcm_" + name.lower().replace("-", "_")
        samples = convert(name)
        encoded = encode(samples)
        lines.append(f"static const uint8_t {symbol}[] PROGMEM = {{")
        for index in range(0, len(encoded), 24):
            lines.append("  " + ", ".join(str(value) for value in encoded[index:index + 24]) + ",")
        lines.extend(["};", f"static const int16_t {symbol}_first = {samples[0]};",
                      f"static const uint32_t {symbol}_frames = {len(samples)};", ""])
    OUTPUT.write_text("\n".join(lines))
    print(f"Wrote {OUTPUT}: {sum(len(convert(name)) for name in SOURCES)} samples")


if __name__ == "__main__":
    main()
